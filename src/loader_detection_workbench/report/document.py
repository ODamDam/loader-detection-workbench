"""Format-neutral report blocks with inert Markdown and HTML renderers.

A report is built once as a sequence of blocks and then rendered to Markdown or
to a self-contained HTML page. Values marked ``trusted`` are generated by the
Workbench itself (display IDs, timestamps, counts). Every other value is
untrusted evidence text: it is forced onto one line and escaped by both
renderers, so it can never introduce markup, links or new report structure.
"""

from __future__ import annotations

import html
import re
from dataclasses import dataclass

from loader_detection_workbench.presentation import markdown_text, single_line


@dataclass(frozen=True, slots=True)
class Text:
    value: str
    trusted: bool = False


@dataclass(frozen=True, slots=True)
class Heading:
    level: int
    text: Text
    # Workbench-generated lead such as a display ID, rendered before ``text``.
    prefix: str = ""


@dataclass(frozen=True, slots=True)
class Item:
    """One bullet; ``label`` is always Workbench-generated."""

    label: str | None
    value: Text


@dataclass(frozen=True, slots=True)
class Bullets:
    items: tuple[Item, ...]


@dataclass(frozen=True, slots=True)
class Paragraph:
    text: Text


@dataclass(frozen=True, slots=True)
class Table:
    headers: tuple[str, ...]
    rows: tuple[tuple[Text, ...], ...]
    numeric: frozenset[int] = frozenset()


@dataclass(frozen=True, slots=True)
class Code:
    """Verbatim multi-line text such as a rule body."""

    content: str


_HREF = re.compile(r"(?:\.\./)?[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*\.html", re.ASCII)


@dataclass(frozen=True, slots=True)
class Links:
    """Navigation between pages of a generated site.

    Targets are Workbench-generated relative ``.html`` paths only; anything
    else is refused, so evidence text can never become a link.
    """

    items: tuple[tuple[str, Text], ...]

    def __post_init__(self) -> None:
        for href, _ in self.items:
            if _HREF.fullmatch(href) is None:
                raise ValueError("link target must be a relative .html path")


type Block = Heading | Bullets | Paragraph | Table | Code | Links


@dataclass(frozen=True, slots=True)
class Document:
    title: str
    blocks: tuple[Block, ...]


def trusted(value: object) -> Text:
    return Text(str(value), trusted=True)


def untrusted(value: object) -> Text:
    return Text(str(value))


def item(label: str | None, value: object, *, is_trusted: bool = False) -> Item:
    return Item(label, Text(str(value), trusted=is_trusted))


def _markdown(text: Text) -> str:
    return text.value if text.trusted else markdown_text(text.value)


def _code_lines(content: str) -> list[str]:
    # Control characters other than line breaks and tabs never reach a report.
    cleaned = "".join(
        character if character in "\n\t" or character.isprintable() else " "
        for character in content.replace("\r\n", "\n").replace("\r", "\n")
    )
    return cleaned.split("\n")


def render_markdown(document: Document) -> str:
    lines = [f"# {document.title}", ""]
    for block in document.blocks:
        if isinstance(block, Heading):
            lines.extend(
                [f"{'#' * block.level} {block.prefix}{_markdown(block.text)}", ""]
            )
        elif isinstance(block, Bullets):
            for entry in block.items:
                value = _markdown(entry.value)
                lines.append(
                    f"- {value}" if entry.label is None else f"- {entry.label}: {value}"
                )
            lines.append("")
        elif isinstance(block, Paragraph):
            lines.extend([_markdown(block.text), ""])
        elif isinstance(block, Links):
            lines.extend(
                f"- [{_markdown(label)}]({href})" for href, label in block.items
            )
            lines.append("")
        elif isinstance(block, Table):
            lines.append("| " + " | ".join(block.headers) + " |")
            lines.append(
                "|"
                + "|".join(
                    "---:" if index in block.numeric else "---"
                    for index in range(len(block.headers))
                )
                + "|"
            )
            for row in block.rows:
                lines.append("| " + " | ".join(_markdown(cell) for cell in row) + " |")
            lines.append("")
        else:
            body = _code_lines(block.content)
            longest = max(
                (len(run) for line in body for run in re.findall(r"`+", line)),
                default=0,
            )
            fence = "`" * max(3, longest + 1)
            lines.extend([fence + "text", *body, fence, ""])
    return "\n".join(lines)


_STYLE = """
:root { color-scheme: light; font-family: system-ui, sans-serif; color: #172033; }
body { margin: 0 auto; max-width: 62rem; padding: 2rem; background: #fff; }
h1 { border-bottom: 2px solid #172033; padding-bottom: .4rem; }
h2 { border-bottom: 1px solid #d9dee8; margin-top: 2.2rem; padding-bottom: .3rem; }
h3 { margin-top: 1.6rem; }
ul { padding-left: 1.2rem; }
li { margin: .2rem 0; overflow-wrap: anywhere; }
table { border-collapse: collapse; width: 100%; font-size: .92rem; }
th, td { border: 1px solid #d9dee8; padding: .4rem .55rem; text-align: left;
  vertical-align: top; overflow-wrap: anywhere; }
th { background: #f4f6f9; }
td.num, th.num { text-align: right; }
pre { background: #f4f6f9; border: 1px solid #d9dee8; overflow-x: auto;
  padding: .8rem 1rem; }
.label { font-weight: 700; }
@media print { body { max-width: none; padding: 0; } }
""".strip()


def _html(text: Text) -> str:
    return html.escape(single_line(text.value), quote=True)


def render_html(document: Document) -> str:
    """Self-contained static page: inline style only, no script or remote resource."""
    title = html.escape(document.title, quote=True)
    parts = [
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta http-equiv="Content-Security-Policy" '
        "content=\"default-src 'none'; style-src 'unsafe-inline'\">",
        '<meta name="referrer" content="no-referrer">',
        f"<title>{title}</title>",
        f"<style>\n{_STYLE}\n</style>",
        "</head>",
        "<body>",
        f"<h1>{title}</h1>",
    ]
    for block in document.blocks:
        if isinstance(block, Heading):
            level = min(max(block.level, 2), 6)
            parts.append(
                f"<h{level}>{html.escape(block.prefix)}{_html(block.text)}</h{level}>"
            )
        elif isinstance(block, Bullets):
            parts.append("<ul>")
            for entry in block.items:
                value = _html(entry.value)
                parts.append(
                    f"<li>{value}</li>"
                    if entry.label is None
                    else f'<li><span class="label">{html.escape(entry.label)}:</span> '
                    f"{value}</li>"
                )
            parts.append("</ul>")
        elif isinstance(block, Paragraph):
            parts.append(f"<p>{_html(block.text)}</p>")
        elif isinstance(block, Links):
            parts.append('<ul class="links">')
            parts.extend(
                f'<li><a href="{html.escape(href, quote=True)}">{_html(label)}</a></li>'
                for href, label in block.items
            )
            parts.append("</ul>")
        elif isinstance(block, Table):
            parts.append("<table>")
            parts.append(
                "<thead><tr>"
                + "".join(
                    f'<th class="num">{html.escape(header)}</th>'
                    if index in block.numeric
                    else f"<th>{html.escape(header)}</th>"
                    for index, header in enumerate(block.headers)
                )
                + "</tr></thead>"
            )
            parts.append("<tbody>")
            for row in block.rows:
                parts.append(
                    "<tr>"
                    + "".join(
                        f'<td class="num">{_html(cell)}</td>'
                        if index in block.numeric
                        else f"<td>{_html(cell)}</td>"
                        for index, cell in enumerate(row)
                    )
                    + "</tr>"
                )
            parts.append("</tbody></table>")
        else:
            body = html.escape("\n".join(_code_lines(block.content)), quote=True)
            parts.append(f"<pre>{body}</pre>")
    parts.extend(["</body>", "</html>", ""])
    return "\n".join(parts)
